import { expect, test } from "@playwright/test";
import { readFileSync } from "node:fs";
import { paceLogin } from "./login-pacing";

test("HR changes an unprepared employee destination inside payroll and sees the new group", async ({ page }) => {
  const f = JSON.parse(readFileSync(process.env.PAYMENT_FIXTURE_FILE!, "utf8")) as { shopId: string; branches: string[]; employees: { id: string; recordId: string; kind: string }[] };
  const employee = f.employees.find(item => item.kind === "cash")!;
  await page.goto("/login");
  await page.getByLabel("ชื่อผู้ใช้", { exact: true }).fill("hr");
  await page.getByLabel("รหัสผ่าน", { exact: true }).fill("password");
  await paceLogin();
  await page.getByRole("button", { name: "เข้าสู่พื้นที่ทำงาน", exact: true }).click();
  await expect(page).not.toHaveURL(/\/login$/);
  await page.goto("/payroll");
  await page.getByRole("combobox", { name: "ร้าน", exact: true }).selectOption(f.shopId);
  await page.getByRole("button", { name: "เปิดสมุดงาน", exact: true }).click();
  await page.getByRole("button").filter({ hasText: "10/2095" }).click();
  const section = page.getByRole("region", { name: "เตรียมจ่ายเงินเดือน", exact: true });
  const row = section.locator(`[data-payment-record="${employee.recordId}"]`);
  await row.getByRole("button", { name: "เลือกช่องทางรับเงิน" }).click();
  await row.getByRole("combobox", { name: "วิธีรับเงินเดือน" }).selectOption("transfer");
  await row.getByLabel("หมายเลขรับเงินพร้อมเพย์").fill("0812345678");
  await row.getByRole("button", { name: "บันทึกช่องทางรับเงิน" }).click();
  await expect(section.getByText("บันทึกช่องทางรับเงินแล้ว กรุณาตรวจกลุ่มและปลายทางก่อนเตรียมจ่าย")).toBeVisible();
  await expect(section.getByRole("region", { name: "จ่ายเงินโอน PromptPay" }).locator(`[data-payment-record="${employee.recordId}"]`)).toBeVisible();
  const saved = await page.request.get(`/api/v1/employees/${employee.id}/payment-destination`);
  expect((await saved.json()).data).toMatchObject({ payment_method: "transfer", promptpay_phone: "0812345678" });
});

test("payment categories and branch summaries remain frozen when employee choices change", async ({ page, baseURL }) => {
  test.setTimeout(120_000);
  const f = JSON.parse(readFileSync(process.env.PAYMENT_CATEGORY_FIXTURE_FILE!, "utf8")) as { shopId: string; periodId: string; branches: string[]; employees: { id: string; recordId: string; kind: string; branchId: string }[] };
  const member = f.employees.find(item => item.kind === "member" && item.branchId === f.branches[0])!;
  const cash = f.employees.find(item => item.kind === "cash" && item.branchId === f.branches[0])!;
  await page.goto("/login");
  await page.getByLabel("ชื่อผู้ใช้", { exact: true }).fill("hr");
  await page.getByLabel("รหัสผ่าน", { exact: true }).fill("password");
  await paceLogin(); await page.getByRole("button", { name: "เข้าสู่พื้นที่ทำงาน", exact: true }).click();
  await expect(page).not.toHaveURL(/\/login$/);
  const headers = { origin: new URL(baseURL!).origin };
  const bank = await page.request.post(`/api/v1/employees/${cash.id}/bank-accounts`, { headers, data: { bank_code: "004", bank_name: "Test bank", account_holder_name: "Test employee", account_number: "1234561234", is_primary: true } });
  expect(bank.ok(), await bank.text()).toBe(true);
  const choose = async (id: string, category: "cash" | "social_security") => {
    await page.goto(`/employees/${id}`);
    await expect(page.getByText("ข้อมูลเดิมยังไม่ได้เลือกประเภทใหม่ ระบบใช้กลุ่มเดิมจนกว่าจะเลือกและบันทึก")).toBeVisible();
    await page.getByRole("combobox", { name: "วิธีรับเงินเดือน", exact: true }).selectOption(category);
    await page.getByLabel("หมายเลขรับเงินพร้อมเพย์", { exact: true }).fill("");
    await page.getByRole("button", { name: "บันทึกช่องทางรับเงิน", exact: true }).click();
    await expect(page.getByRole("status").filter({ hasText: "บันทึกช่องทางรับเงินแล้ว" })).toBeVisible();
  };
  await choose(member.id, "cash");
  await choose(cash.id, "social_security");
  await page.goto("/payroll");
  await page.getByRole("combobox", { name: "ร้าน", exact: true }).selectOption(f.shopId);
  await page.getByRole("button", { name: "เปิดสมุดงาน", exact: true }).click();
  await page.getByRole("button").filter({ hasText: "10/2095" }).click();
  const panel = page.getByRole("region", { name: "เตรียมจ่ายเงินเดือน", exact: true });
  await expect(panel.getByRole("region", { name: "จ่ายเงินสด" }).locator(`[data-payment-record="${member.recordId}"]`)).toBeVisible();
  await expect(panel.getByRole("region", { name: "จ่ายแบบประกันสังคม" }).locator(`[data-payment-record="${cash.recordId}"]`)).toBeVisible();
  const summary = panel.getByRole("table");
  await expect(summary.getByRole("row").filter({ hasText: "Payment 1" })).toContainText("100.01 บาท · 1 คน");
  await panel.getByRole("combobox", { name: "สาขาสำหรับเตรียมจ่าย", exact: true }).selectOption(f.branches[0]);
  await panel.getByRole("button", { name: "เตรียมจ่ายสาขาที่เลือก", exact: true }).click();
  await expect(panel.getByText("เตรียมจ่ายแล้ว เก็บปลายทางและยอดเงินตามข้อมูลขณะเตรียม ยังไม่ถือว่าจ่ายเงินแล้ว")).toBeVisible();
  await page.goto(`/employees/${cash.id}`);
  await page.getByRole("combobox", { name: "วิธีรับเงินเดือน", exact: true }).selectOption("cash");
  await page.getByLabel("หมายเลขรับเงินพร้อมเพย์", { exact: true }).fill("");
  await page.getByRole("button", { name: "บันทึกช่องทางรับเงิน", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "บันทึกช่องทางรับเงินแล้ว" })).toBeVisible();
  const saved = await page.request.get(`/api/v1/payroll/periods/${f.periodId}/payments`);
  const rows = (await saved.json()).data;
  expect(rows.find((row: { payroll_record_id: string }) => row.payroll_record_id === cash.recordId)).toMatchObject({ group: "social_security", payment_method: "transfer", amount: "100.01" });
});
