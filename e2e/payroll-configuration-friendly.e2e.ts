import { test, expect } from "@playwright/test";
import { paceLogin } from "./login-pacing";

test("people enter social security as a percentage when creating and changing a value", async ({ page, baseURL }) => {
  await page.goto("/login");
  await page.getByLabel("ชื่อผู้ใช้", { exact: true }).fill("admin");
  await page.getByLabel("รหัสผ่าน", { exact: true }).fill("password");
  await paceLogin(); await page.getByRole("button", { name: "เข้าสู่พื้นที่ทำงาน", exact: true }).click();
  await expect(page).not.toHaveURL(/\/login$/);
  const createdShop = await page.request.post("/api/v1/shops", { headers: { origin: new URL(baseURL!).origin }, data: { name: `Config ${Date.now()}` } });
  expect(createdShop.ok(), await createdShop.text()).toBe(true);
  const shop = (await createdShop.json()).data;
  await page.goto("/payroll");
  await page.getByRole("combobox", { name: "ร้าน", exact: true }).selectOption(shop.id);
  await page.getByRole("button", { name: "เปิดสมุดงาน", exact: true }).click();
  const form = page.locator("form").filter({ has: page.getByRole("button", { name: "บันทึกค่าคำนวณ", exact: true }) });
  await expect(page.getByText(/จำนวนวันทำงานมาตรฐานคำนวณอัตโนมัติ/)).toBeVisible();
  await expect(form.locator('option[value="STANDARD_WORK_DAYS"]')).toHaveCount(0);
  await form.getByRole("combobox", { name: "ค่าคำนวณ", exact: true }).selectOption("SOCIAL_SECURITY_RATE");
  await expect(form.getByText(/กรอก 5 สำหรับอัตรา 5%/)).toBeVisible();
  await form.getByLabel("ค่า (%)", { exact: true }).fill("5");
  await form.getByLabel("เริ่มใช้", { exact: true }).fill("2026-01-01");
  const save = page.waitForResponse(r => r.url().endsWith("/api/v1/payroll/configurations") && r.request().method() === "POST");
  await form.getByRole("button", { name: "บันทึกค่าคำนวณ", exact: true }).click();
  const response = await save;
  expect(response.ok(), await response.text()).toBe(true);
  const created = (await response.json()).data;
  expect(created.numeric_value).toBe("0.0500");
  await page.getByText(/ความพร้อมของค่าคำนวณ \(/).click();
  const row = page.getByRole("row").filter({ hasText: "อัตราประกันสังคม" });
  await expect(row.getByText("5 %", { exact: true })).toBeVisible();
  await row.getByText("เปลี่ยนค่าตั้งแต่วันที่", { exact: true }).click();
  await expect(row.getByLabel("ค่าใหม่ (%)", { exact: true })).toHaveValue("5");
  await row.getByLabel("ค่าใหม่ (%)", { exact: true }).fill("6");
  await row.getByLabel("วันที่เริ่มใช้ค่าใหม่", { exact: true }).fill("2026-02-01");
  const successor = page.waitForResponse(r => r.url().includes(`/configurations/${created.id}/successor`) && r.request().method() === "POST");
  await row.getByRole("button", { name: "บันทึกช่วงใหม่", exact: true }).click();
  const result = await successor;
  expect(result.ok(), await result.text()).toBe(true);
  expect((await result.json()).data.numeric_value).toBe("0.0600");
});
