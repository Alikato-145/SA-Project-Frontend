import { test, expect } from "@playwright/test";
import { paceLogin } from "./login-pacing";
test("MOCK26 payroll link loads pending overtime for Demo Employee", async ({ page }) => {
  test.skip(process.env.MOCK26_OT_FIXTURE !== "1" || !process.env.MOCK26_TEST_PASSWORD, "Requires isolated MOCK26 fixture and pending OT");
  await page.goto('/login');
  await page.getByLabel('ชื่อผู้ใช้', { exact: true }).fill(process.env.MOCK26_TEST_USER ?? 'mock26_hr');
  await page.getByLabel('รหัสผ่าน', { exact: true }).fill(process.env.MOCK26_TEST_PASSWORD!);
  await paceLogin(); await page.getByRole('button',{name:'เข้าสู่พื้นที่ทำงาน',exact:true}).click();
  await expect(page).not.toHaveURL(/\/login$/);
  await page.goto('/payroll');
  await page.getByRole('combobox',{name:'ร้าน',exact:true}).selectOption({label:'MOCK26 · ร้าน Mock Haris 2026'});
  await page.getByRole('button',{name:'เปิดสมุดงาน',exact:true}).click();
  await page.getByRole('button',{name:/10\/2026/}).click();
  const advance=page.getByRole('row').filter({hasText:'เงินทดรอง รอพิจารณา'});
  await advance.getByRole('link',{name:'ไปตรวจคำขอ'}).click();
  await expect(page).toHaveURL(/finance\?employee_id=/);
  await expect(page.getByPlaceholder('ค้นหาชื่อหรือรหัสพนักงาน').first()).toHaveValue(/MOCK26-EMPLOYEE/);
  await page.getByRole('button',{name:'โหลดข้อมูลการเงิน',exact:true}).click();
  await expect(page.getByText('เงินทดรองตัวอย่าง',{exact:true})).toBeVisible();
  const employeeId = new URL(page.url()).searchParams.get('employee_id');
  await page.goto(`/leave?employee_id=${employeeId}`);
  await expect(page.getByPlaceholder('ค้นหาชื่อหรือรหัสพนักงาน').first()).toHaveValue(/MOCK26-EMPLOYEE/);
  await page.getByRole('button',{name:'โหลดคำขอ',exact:true}).click();
  await expect(page.getByText('คำขอลาตัวอย่าง',{exact:true})).toBeVisible();
  await page.goto('/payroll');
  await page.getByRole('combobox',{name:'ร้าน',exact:true}).selectOption({label:'MOCK26 · ร้าน Mock Haris 2026'});
  await page.getByRole('button',{name:'เปิดสมุดงาน',exact:true}).click();
  await page.getByRole('button',{name:/10\/2026/}).click();
  const row=page.getByRole('row').filter({hasText:'มี OT รอพิจารณา'});
  await expect(row).toContainText('Demo Employee');
  await expect(page.getByRole('row').filter({hasText:'เงินทดรอง รอพิจารณา'})).toContainText('Demo Employee');
  await row.getByRole('link',{name:'ไปตรวจคำขอ'}).click();
  await expect(page.getByPlaceholder('ค้นหาชื่อหรือรหัสพนักงาน').first()).toHaveValue(/MOCK26-EMPLOYEE/);
  await expect(page.getByText('OT ตัวอย่าง',{exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'อนุมัติ',exact:true})).toBeVisible();
});
