test("OWNER creates an effective membership successor through employment UI", async ({ page, baseURL }) => {
  test.setTimeout(120000);
  const origin = new URL(baseURL!).origin;
  await login(page, "admin");
  const shops = (await (await page.request.get("/api/v1/shops?search=DEMO&is_active=true")).json()).data;
  const shop = shops.find((item: { code: string }) => item.code === "DEMO");
  const branches = (await (await page.request.get(`/api/v1/branches?shop_id=${shop.id}`)).json()).data;
  const branch = branches.find((item: { is_active: boolean }) => item.is_active);
  const departments = (await (await page.request.get(`/api/v1/departments?branch_id=${branch.id}`)).json()).data;
  const positions = (await (await page.request.get(`/api/v1/positions?shop_id=${shop.id}`)).json()).data;
  const department = departments.find((item: { is_active: boolean }) => item.is_active);
  const position = positions.find((item: { is_active: boolean }) => item.is_active);
  const code = `MEM-${Date.now()}`;
  const response = await page.request.post("/api/v1/employees/onboard", { headers: { origin }, data: { employee: { employee_code: code, passport_id: code, first_name: "Member", last_name: "History", hire_date: "2096-01-01" }, assignment: { branch_id: branch.id, department_id: department.id, position_id: position.id, employment_type: "full_time", base_salary: "18000.00", welfare_amount: "0.00", effective_from: "2096-01-01", is_social_security_member: true } } });
  expect(response.ok()).toBe(true);
  const employee = (await response.json()).data.employee.id;
  await page.goto(`/employees/${employee}/employment`);
  await page.getByRole("combobox", { name: "ร้าน", exact: true }).selectOption(shop.id);
  await page.getByRole("combobox", { name: "สาขา", exact: true }).selectOption(branch.id);
  await page.getByRole("combobox", { name: "แผนก", exact: true }).selectOption(department.id);
  await page.getByRole("combobox", { name: "ตำแหน่ง", exact: true }).selectOption(position.id);
  await page.getByRole("checkbox", { name: "สมาชิกประกันสังคมในช่วงการจ้างใหม่" }).uncheck();
  await page.locator('[name="effective_from"]').fill("2096-01-16");
  await page.getByRole("button", { name: "บันทึกช่วงใหม่", exact: true }).click();
  await expect(page.getByText("เพิ่มช่วงการจ้างใหม่แล้ว ประวัติเดิมยังคงอยู่", { exact: true })).toBeVisible();
  const assignments = (await (await page.request.get(`/api/v1/employees/${employee}/assignments`)).json()).data;
  expect(assignments).toHaveLength(2);
  expect(assignments[0]).toMatchObject({ effective_from: "2096-01-01", effective_to: "2096-01-15", is_social_security_member: true });
  expect(assignments[1]).toMatchObject({ effective_from: "2096-01-16", effective_to: null, is_social_security_member: false });
  await expect(page.getByRole("definition").filter({ hasText: "ไม่เป็นสมาชิก" })).toBeVisible();
  await page.screenshot({ path: `${process.env.E2E_EVIDENCE_DIR ?? "/private/tmp"}/haris-task6-owner-membership.png`, fullPage: true });
});
